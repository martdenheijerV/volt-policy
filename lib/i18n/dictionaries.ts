export const DICTIONARIES: Record<Lang, Dict> = { en, nl, de, fr, it, es };

export function t(lang: Lang | string | null | undefined, key: string): string {
  const l = (lang && (SUPPORTED_LANGUAGES as readonly string[]).includes(lang)
    ? (lang as Lang)
    : "en") as Lang;
  return DICTIONARIES[l][key] ?? DICTIONARIES.en[key] ?? key;
}
